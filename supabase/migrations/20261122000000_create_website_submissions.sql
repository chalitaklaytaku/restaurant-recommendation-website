create table if not exists public.suggested_places (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 160),
  category text not null default '',
  menu text not null default '',
  level text not null default '',
  location text not null check (char_length(location) between 1 and 500),
  reason text not null default '',
  author text not null default 'สมาชิกชุมชนนางรอง',
  created_at timestamptz not null default now()
);

alter table public.suggested_places enable row level security;
grant select, insert on public.suggested_places to anon, authenticated;
grant usage, select on sequence public.suggested_places_id_seq to anon, authenticated;

create policy "Anyone can view suggested places"
  on public.suggested_places for select
  to anon, authenticated
  using (true);

create policy "Anyone can submit a suggested place"
  on public.suggested_places for insert
  to anon, authenticated
  with check (true);

create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  respondent_name text not null default 'ผู้ใช้งานทั่วไป',
  respondent_gender text not null default 'ไม่ระบุ',
  respondent_age text not null default 'ไม่ระบุ',
  scores jsonb not null check (jsonb_typeof(scores) = 'object'),
  comment text not null default '',
  created_at timestamptz not null default now()
);

alter table public.survey_responses enable row level security;
grant insert on public.survey_responses to anon, authenticated;

create policy "Anyone can submit a survey response"
  on public.survey_responses for insert
  to anon, authenticated
  with check (
    jsonb_typeof(scores) = 'object'
    and char_length(comment) <= 4000
  );
